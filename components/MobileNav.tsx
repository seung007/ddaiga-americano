/**
 * 모바일 진입로 — **768px 미만에서 헤더 메뉴가 통째로 안 보인다.**
 *
 * ─────────────────────────────────────────────────────────────
 * 왜 만들었나 (2026-09-21 측정, 2026-09-22 반영)
 *
 * 사이트 주인의 말: *"다 만들었는데 왜 없어"*
 * 기능은 전부 배포돼 있었다. **안 보이는 건 헤더 메뉴였다.**
 *
 * 배포본 591px 에서 `offsetWidth` 실측:
 *   러닝화 0 · 러닝 가이드 0 · 코스 0 · 대회 일정 0 · 자유게시판 0 · 신발 찾기 79px
 *
 * `SiteHeader.tsx` 의 링크가 `md:block` 이라 5개가 전부 숨는다. 방문자의 약 80%가 모바일이다.
 * **그 사람들은 이 사이트의 메뉴를 본 적이 없다.**
 *
 * ⚠️ `md:` 를 되돌리지 마라. 그 값은 playwright 로 폭별로 재서 정했다
 * (`SiteHeader.tsx` 56~73행). 항목을 6개로 늘리면 640·672px 에서 두 줄로 쪼개진다.
 * *"읽을 수 없는 메뉴는 없는 메뉴보다 나쁘다"* 는 2026-09-08 의 판단은 지금도 맞다.
 *
 * ─────────────────────────────────────────────────────────────
 * 진짜 문제는 홈이 아니라 **글 페이지**였다
 *
 * 홈은 이미 대비가 돼 있었다 — 히어로 밑에 칩 4개가 깔려 있었다(2026-09-18).
 * 그런데 **네이버 유입이 도착하는 곳은 홈이 아니라 `/injury/*` 다.**
 *
 * `/injury/achilles` · 375×812 실측:
 *   · 헤더에 보이는 것 = 로고 + 「신발 찾기」 **둘뿐**
 *   · `/races` 로 가는 보이는 링크 = **푸터 1개**
 *   · 푸터 시작 위치 = **5446px = 6.7 화면 아래**
 *
 * GA4 28일 기준 스크롤하는 사람이 40% 다. 6.7 화면을 내려가는 비율은 그보다 훨씬 낮다.
 * **글을 읽고 나가는 사람에게 사이트의 나머지는 존재하지 않았다.**
 * 대회 55건을 크롤링하고 상세를 만들고 게시판을 갈아엎은 게 전부 여기서 막혔다.
 *
 * ─────────────────────────────────────────────────────────────
 * 왜 햄버거 메뉴가 아닌가
 *
 * 홈에서 **이미 배포돼 안 깨지는 게 확인된 UI** 를 그대로 옮겼다.
 * 햄버거는 JS·열림 상태·바깥 클릭·포커스 처리가 붙고, **클릭이 한 번 더 는다.**
 * 이 저장소는 *"클릭 한 번에서 대부분을 잃는다"* 를 여러 번 기록했다.
 *
 * ⚠️ **항목을 5개로 늘리지 마라.** 375px 에서 4개가 딱 1줄(높이 34px)이다.
 * 「코스」가 빠진 건 의도다 — 하나를 골라야 한다면 대회·게시판이 재방문 축이다.
 *
 * ⚠️ **`sticky` 를 붙이지 마라.** 스크롤 내내 따라다니면 모바일 세로를 상시로 먹는다.
 * 헤더(`sticky top-0`)만 따라다니고 이 줄은 위로 흘려보낸다.
 */

/** 헤더 메뉴 5개 중 4개. 순서는 홈 히어로에 있던 것을 그대로 옮겼다 */
const LINKS: [string, string][] = [
  ["/shoes", "러닝화"],
  ["/races", "대회 일정"],
  ["/injury", "가이드"],
  ["/community", "게시판"],
];

export default function MobileNav() {
  return (
    <nav
      aria-label="주요 메뉴"
      className="border-b border-gray-100 bg-white md:hidden"
    >
      {/* max-w-3xl · px-6 은 SiteHeader 안쪽 컨테이너와 같은 값이다 (좌측 정렬을 맞춘다) */}
      <div className="mx-auto flex max-w-3xl gap-2 overflow-x-auto px-6 py-2">
        {LINKS.map(([href, label]) => (
          <Link
            key={href}
            href={href}
            className="shrink-0 whitespace-nowrap rounded-full border border-gray-300 bg-white px-3 py-1.5 text-sm text-gray-700 transition-colors hover:border-emerald-400 hover:text-emerald-700"
          >
            {label}
          </Link>
        ))}
      </div>
    </nav>
  );
}
