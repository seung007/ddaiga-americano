import { hasAnyAffiliate } from "@/lib/shoes/affiliate";

/**
 * 공정위 경제적 이해관계 고지.
 *
 * 규정 근거
 * ─────────
 * 「추천·보증 등에 관한 표시·광고 심사지침」 2024-12-01 시행 개정에서
 * 문자 중심 매체는 **게시물의 제목 또는 첫 부분**에 경제적 이해관계를 밝히도록 바뀌었다.
 * 이전에 허용되던 "끝 부분 표시"는 폐지됐다. 그래서 이 배너는 페이지 맨 위에 둔다.
 *
 * 왜 스위치가 없는가
 * ──────────────────
 * `hasAnyAffiliate()`가 제휴 링크 등록 여부를 보고 스스로 켜진다.
 * 수동 플래그를 두면 링크를 넣고 고지를 잊는 순간 **표시 없는 광고**가 된다.
 * 반대로 링크를 다 뺐는데 고지가 남으면 하지도 않은 제휴를 밝히는 셈이라
 * 그것도 정확하지 않다. 데이터에서 파생시키면 둘 다 생기지 않는다.
 *
 * 문구에 대해
 * ───────────
 * "추천 순서는 광고비로 바뀌지 않습니다"는 기존 문구이고 여전히 참이다 —
 * 추천 알고리즘은 제휴 여부를 보지 않는다(lib/shoes/recommend.ts 어디에도
 * 제휴 관련 가중치가 없다). 다만 그 문장은 **수수료를 받는다는 사실 자체를
 * 밝히지 않으므로** 고지로는 부족하다. 그래서 둘을 함께 적는다.
 *
 * ⚠️ 쿠팡이 요구하는 문구는 **글자 그대로** 넣는다 (2026-09-08 확인)
 * ───────────────────────────────────────────────────────────────
 * 파트너스 링크 생성 화면이 "아래 문구를 **반드시** 기재해 주세요"라며 이 문장을 준다:
 *
 *   "이 포스팅은 쿠팡 파트너스 활동의 일환으로, 이에 따른 일정액의 수수료를 제공받습니다."
 *
 * 같은 화면에 **"활동 준수 사항을 지키지 않으면 수익금 지급이 중단될 수 있습니다"**
 * 라고 적혀 있다. 그래서 의미가 같아도 **바꿔 쓰지 않는다.**
 *
 * 원래 이 컴포넌트에는 "일정액의 수수료를 받습니다"라는 **내 표현**만 있었다.
 * 뜻은 같지만 쿠팡이 요구한 문장은 아니다 — 심사가 문구 일치를 본다면 그건
 * 지키지 않은 것이 된다. 판정 기준을 내가 정할 수 없는 곳에서는 **원문을 쓴다.**
 *
 * "포스팅"이라는 단어가 이 사이트 문맥에 어색해도 그대로 둔다. 어색한 것과
 * 지급이 중단되는 것 중 무엇이 더 나쁜지는 비교가 안 된다.
 */

/** 쿠팡 파트너스가 요구하는 원문. **수정하지 마세요.** */
const COUPANG_REQUIRED_NOTICE =
  "이 포스팅은 쿠팡 파트너스 활동의 일환으로, 이에 따른 일정액의 수수료를 제공받습니다.";

/**
 * 2026-09-17 — **작게, 한 줄로.** hyun 님 지적: *"크게 표시하면 돈 받을 거야 느낌이다."*
 *
 * 맞는 지적이라 노란 상자·굵은 글씨·설명 두 문장을 뺐다. 다만 **"맨 아래 잘 안 보이게"는 못 한다.**
 * 개정 심사지침(2024-12-01 시행)이 문자 매체는 **제목 또는 첫 부분**에, 본문보다 크거나
 * **글자색을 달리해** 쉽게 인식되게 두라고 한다. 「더보기」·링크 뒤·끝 부분은 인정되지 않는다.
 * 그래서 **위치는 첫 부분 그대로, 크기만 줄이고 색으로 구별**한다.
 *
 * 그리고 **제휴 링크가 실제로 있는 페이지에만** 띄운다(`show`). 전에는 제휴 링크가 3켤레뿐인데
 * 러닝화 목록·52개 상세 전부에 떴다 — 하지도 않는 제휴를 밝히는 셈이었다.
 */
export default function AffiliateNotice({ show = hasAnyAffiliate() }: { show?: boolean }) {
  if (!show) return null;

  return (
    <p className="mb-4 text-xs text-amber-700">
      {COUPANG_REQUIRED_NOTICE} 구매자가 더 내는 금액은 없습니다.
    </p>
  );
}
