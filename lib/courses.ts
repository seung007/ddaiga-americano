/**
 * 한강 러닝 코스 — 코스 원장
 *
 * 왜 원장 형태인가 (2026-09-06)
 * ─────────────────────────────
 * **나는 이 코스들을 달려본 적이 없다.** 그러니 거리·시설·접근로를 기억이나 인상으로
 * 채우면 `AGENTS.md`가 금지하는 바로 그것이 된다 — 유튜브 채널명 40개를 지어냈던 것과
 * 같은 실패다. 그래서 신발 `verified.json`과 같은 방식을 쓴다.
 *
 *   · 모든 수치에 **출처 URL과 확인 날짜**를 붙인다
 *   · 확인 못 한 항목은 **비운다**. 그럴듯하게 채우지 않는다
 *   · 출처는 **서울시 미래한강본부 공식 자료**만 쓴다
 *
 * 실제로 이 파일 초안에서 **지하철 출구 번호를 지어냈다.**
 * "뚝섬유원지역 2·3번 출구"라고 썼는데 공식 안내는 **7호선 자양역 2·3번 출구**였고,
 * 잠실은 "잠실역"이라고 썼는데 공식 권장은 **잠실나루역 3·4번 출구**였다.
 * 그럴듯한 구체성이 작화의 신호라는 규칙이 또 맞았다. 지금 값은 전부 공식 페이지에서
 * 옮긴 것이고, 반포 안내센터 번호는 **확인하지 못해 비워 뒀다.**
 *
 * `lengthKm`은 **서울시가 고시한 공원 길이**다. 러닝 코스 거리가 아니다.
 * 이 구분이 중요하다 — 러닝 앱·블로그가 공원 길이를 "코스 거리"로 옮겨 적고 있고,
 * 어떤 앱은 잠실을 7.0km로 적었는데 **공식 공원 길이는 4.8km**다.
 * 우리는 공식 길이만 쓰고, 왕복이면 2배라고만 적는다. **구간 거리는 지어내지 않는다** —
 * "마포대교까지 3.2km" 같은 숫자는 실측이 필요한데 나는 실측할 수 없다.
 *
 * 노면(우레탄·아스팔트 구간 위치)도 **공식 자료에 없어서 적지 않았다.**
 * 한강공원 산책로가 포장로라는 것과 강변 둔치라 평탄하다는 것까지가 확인된 사실이다.
 *
 * **신발은 여기 없다.** 초안에는 코스마다 `shoeIds`가 있었는데 뺐다.
 * 네 곳 다 포장로·평탄이라 코스가 바꾸는 건 '한 번에 얼마나 오래 달리는가' 하나뿐이고,
 * 그건 코스 데이터가 아니라 `lengthKm`에서 바로 나온다. 코스마다 모델을 박아 두면
 * 코스 글이 신발 글이 되고, 신발이 단종되면 코스 데이터까지 낡는다.
 *
 * ⚠️ 지도를 베끼지 않았다. 카카오맵·네이버지도 화면을 따라 그리면 2차적 저작물
 * 소지가 있다. 아래 `bridges`는 **다리 이름과 상류→하류 순서**라는 사실만 담고,
 * `CourseFigure`는 그 사실로 개략 도식을 그린다. 축척도 좌표도 실제와 다르다.
 */

