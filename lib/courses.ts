  access: string[];
  /** 공식 안내센터 전화. 확인 못 했으면 null */
  info: string | null;
  /** 공식 자료에서 확인한 것만 */
  facts: string[];
  /** 이 코스를 어떤 러너에게 권하는가 — 거리와 포장 상태에서만 도출한다 */
