/**
 * 소스에서 주석만 지운다 — **줄 수와 줄 길이는 유지한다.**
 *
 * ─────────────────────────────────────────────────────────────
 * 왜 공용으로 뺐나 (2026-09-08)
 *
 * 같은 오탐을 **두 번** 맞았다.
 *
 *   ① `check-cdn.mjs` 에 `<svg><title>` 금지를 넣은 직후 오탐 5건.
 *      금지 규칙을 설명하는 내 주석 안의 `<title>` 을 코드로 읽었다.
 *   ② `check-internal-links.mjs` 가 `lib/brands.ts` 의 주석에 적힌
 *      백틱 경로(`/compare/[slug]`)를 **없는 경로로 거는 링크**로 신고했다.
 *
 * 두 번째는 첫 번째를 고치고 나서 났다. 즉 **고친 것이 그 파일에만 남아 있었다.**
 * 검사기를 새로 만들 때마다 같은 함정을 다시 밟게 되므로 한 곳에 둔다.
 *
 * 이 저장소의 규칙: **범위를 넓히면 오탐부터 잡아라.**
 * 오탐이 남은 검사는 사람이 곧 무시하게 되고, 그러면 검사가 없는 것과 같다.
 *
 * ─────────────────────────────────────────────────────────────
 * 왜 "같은 길이의 공백"인가
 *
 * 지워 버리면 줄 번호가 밀려서 `파일:줄` 신고가 엉뚱한 곳을 가리킨다.
 * 사람이 그 줄을 열었을 때 아무것도 없으면 검사를 신뢰하지 않게 된다.
 * 그래서 문자를 **공백으로 치환**해 좌표를 보존한다.
 *
 * ⚠️ 한계: 문자열 리터럴 안의 `//` 나 `/* *` 는 구분하지 않는다.
 * 정규식 리터럴(`/\/\//`)도 그렇다. 정확히 하려면 파서가 필요하지만,
 * 이 검사들의 목적(금지 패턴·링크 수집)에는 이 정도가 충분하고
 * **오탐을 줄이는 방향으로만 틀린다** — 코드를 주석으로 잘못 보면
 * 검사가 놓치는 쪽(거짓 음성)이지 사람을 괴롭히는 쪽은 아니다.
 * 놓치는 게 문제가 되기 시작하면 그때 파서를 붙인다.
 */
export function stripComments(src) {
  // 블록 주석 — 개행만 남기고 나머지는 공백으로.
  const noBlock = src.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "));

  return noBlock
    .split("\n")
    .map((line) => {
      const t = line.trimStart();
      // 줄 주석과, 블록 주석이 지워지고 남은 JSDoc 잇줄(`*`).
      if (t.startsWith("//") || t.startsWith("*")) return " ".repeat(line.length);
      const i = line.indexOf("//");
      return i >= 0 ? line.slice(0, i) + " ".repeat(line.length - i) : line;
    })
    .join("\n");
}
